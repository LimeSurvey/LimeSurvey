import { useParams } from 'react-router-dom'
import classNames from 'classnames'

import {
  useBuffer,
  useExpressionScriptValidation,
  useFocused,
  useIsConditionRelevancePending,
  useSurvey,
} from 'hooks'
import {
  getQuestionById,
  htmlPopup,
  QUESTION_RELEVANCE_DEFAULT_VALUE,
} from 'helpers'
import { Button } from 'components/UIComponents'
import { CloseCircleIcon, ExpandIcon } from 'components/icons'

import { ExpressionScriptEditorOverlay } from '../Overlays'
import { handleConditionScriptUpdate } from './handleConditionScriptUpdate'
import { showResetAllConditionsOverlay, showWarningMessage } from '../utils'

export const ExpressionScriptInputBox = ({ onShowPanel, onNavigateBack }) => {
  const { surveyId } = useParams()
  const { survey, update } = useSurvey(surveyId)
  const { focused, groupIndex, questionIndex } = useFocused()
  const { addToBuffer } = useBuffer()

  const question = getQuestionById(focused.qid, survey).question
  const validateExpression = useExpressionScriptValidation(
    surveyId,
    question.qid
  )
  const hasConditions = (question?.scenarios ?? []).length > 0
  // The relevance is generated by the server from the conditions, so it's stale until they are saved.
  // Editing the script now could also reach the server after the conditions and delete them.
  const isRelevancePending = useIsConditionRelevancePending(question)
  const pendingHint = t(
    'The expression script will be editable once the conditions are saved.'
  )

  const maybeShowConditionsOverwriteWarning = () => {
    if (hasConditions) {
      showWarningMessage(
        t(
          `Conditions written in ExpressionScript mode can't be displayed inside the visual condition builder.`
        ),
        'bottom-center'
      )
    }
  }

  const handleApply = (newExpressionScript) => {
    handleConditionScriptUpdate(
      newExpressionScript,
      survey,
      questionIndex,
      groupIndex,
      addToBuffer,
      update,
      onNavigateBack
    )
  }

  return (
    <div
      className={classNames('condition-script-trigger', {
        pending: isRelevancePending,
      })}
      title={isRelevancePending ? pendingHint : undefined}
      aria-disabled={isRelevancePending}
      data-testid="condition-script-trigger"
    >
      <span
        className="text-muted text-truncate"
        style={{ cursor: isRelevancePending ? 'not-allowed' : 'pointer' }}
        onClick={() => {
          if (isRelevancePending) return
          onShowPanel(null, false, true)
          maybeShowConditionsOverwriteWarning()
        }}
      >
        {isRelevancePending ? (
          <span
            className="condition-script-pending-label"
            data-testid="condition-script-pending"
          >
            {t('Pending sync...')}
          </span>
        ) : question?.relevance === QUESTION_RELEVANCE_DEFAULT_VALUE ? (
          t('Enter expression...')
        ) : (
          question?.relevance || ''
        )}
      </span>
      <div className="d-flex gap-2">
        <Button
          className="d-flex align-items-center p-0 text-secondary"
          variant="link"
          disabled={isRelevancePending}
          onClick={() => {
            htmlPopup({
              html: (
                <ExpressionScriptEditorOverlay
                  question={question}
                  onApply={handleApply}
                  validateExpression={validateExpression}
                />
              ),
              title: '',
              showCloseButton: false,
              width: '1156px',
            })
            maybeShowConditionsOverwriteWarning()
          }}
        >
          <ExpandIcon />
        </Button>
        {question?.relevance &&
          question.relevance !== QUESTION_RELEVANCE_DEFAULT_VALUE && (
            <Button
              className="d-flex align-items-center p-0"
              variant="link"
              disabled={isRelevancePending}
              onClick={() => {
                showResetAllConditionsOverlay({
                  onConfirmDelete: () => handleApply('1'),
                })
              }}
            >
              <CloseCircleIcon />
            </Button>
          )}
      </div>
    </div>
  )
}
