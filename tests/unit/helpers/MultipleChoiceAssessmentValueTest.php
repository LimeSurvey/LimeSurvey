<?php

namespace ls\tests\unit\helpers;

use ls\tests\DummyController;
use ls\tests\TestBaseClass;

/**
 * The .value of a checked multiple choice subquestion is the assessment value of the question.
 *
 * @see https://bugs.limesurvey.org/view.php?id=15549
 */
class MultipleChoiceAssessmentValueTest extends TestBaseClass
{
    /**
     * Response values by question code and subquestion code
     * @var array<string, string>
     */
    private const RESPONSES = [
        'MC_SQ001' => 'Y',
        'MC_SQ002' => '',
        'MC_other' => 'sometext',
        'MCC_SQ001' => 'Y',
        'MCC_SQ001comment' => 'mycomment',
        'MCC_SQ002' => '',
    ];

    /**
     * Expected results with assessments active (assessment value 3 for MC, 2 for MCC)
     * @var array<string, string>
     */
    private const EXPECTED = [
        'MC_SQ001.value' => '3',
        'MC_SQ002.value' => '',
        'MC_other.value' => 'sometext',
        'MCC_SQ001.value' => '2',
        'MCC_SQ001comment.value' => 'mycomment',
        'MCC_SQ002.value' => '',
        'MC_SQ001' => 'Y',
        'MCC_SQ001' => 'Y',
    ];

    /**
     * Import and activate the survey (assessments active, multiple choice question MC
     * with assessment value 3 and "other", multiple choice with comments question MCC with assessment value 2)
     */
    public static function setUpBeforeClass(): void
    {
        parent::setUpBeforeClass();

        $_POST = [];
        $_SESSION = [];

        $surveyFile = self::$surveysFolder . '/limesurvey_survey_615549_multiple_choice_assessment_value.lss';
        self::importSurvey($surveyFile);
        self::$testHelper->activateSurvey(self::$surveyId);
    }

    /**
     * Reset request and session data
     */
    public function tearDown(): void
    {
        $_GET = [];
        $_POST = [];
        $_SESSION = [];
        parent::tearDown();
    }

    /**
     * With assessments active, .value of a checked subquestion is the assessment value,
     * an unchecked subquestion is empty, the "other" text and comments keep their text.
     */
    public function testValueIsAssessmentValue()
    {
        $this->startSurveyWithResponses(true);

        foreach (self::EXPECTED as $expression => $expected) {
            $this->assertSame($expected, $this->processString('{' . $expression . '}'), $expression);
        }
        $this->assertSame('5', $this->processString('{sum(MC_SQ001.value, MC_SQ002.value, MCC_SQ001.value)}'));
    }

    /**
     * Without assessments, .value of a checked subquestion is 0, as for single choice questions.
     */
    public function testValueWithoutAssessments()
    {
        $this->startSurveyWithResponses(false);

        $this->assertSame('0', $this->processString('{MC_SQ001.value}'));
        $this->assertSame('', $this->processString('{MC_SQ002.value}'));
        $this->assertSame('sometext', $this->processString('{MC_other.value}'));
    }

    /**
     * The JavaScript LEMval() returns the same values, using the variable attributes generated by PHP.
     */
    public function testJavaScriptValueIsAssessmentValue()
    {
        $fieldnames = $this->startSurveyWithResponses(true);

        $LEM = \LimeExpressionManager::singleton();
        $varNameAttr = (new \ReflectionProperty($LEM, 'varNameAttr'))->getValue($LEM);
        $alias2varName = (new \ReflectionProperty($LEM, 'alias2varName'))->getValue($LEM);
        $inputValues = [];
        foreach (self::RESPONSES as $code => $value) {
            $inputValues[$fieldnames[$code]] = $value;
        }

        $js = "global.\$ = function() { return { on: function() {}, val: function() { return ''; }, text: function() { return ''; } }; };\n"
            . 'const inputValues = ' . json_encode($inputValues) . ";\n"
            . "global.document = { getElementById: function(id) {\n"
            . "    if (id.indexOf('relevance') === 0) { return {value: 1}; }\n"
            . "    const fieldname = id.replace(/^(java|answer)/, '');\n"
            . "    return {value: (fieldname in inputValues) ? inputValues[fieldname] : ''};\n"
            . "} };\n"
            . "global.Decimal = require(process.cwd() + '/node_modules/decimal.js/decimal.js');\n"
            . "eval(fs.readFileSync('./assets/packages/expressions/em_javascript.js', {encoding: 'utf8'}));\n"
            . "LEMradix = '.';\nLEMmode = 'survey';\nLSvar = {};\n"
            . 'LEMalias2varName = {' . implode(',', array_column($alias2varName, 'jsPart')) . "};\n"
            . 'LEMvarNameAttr = {' . implode(',', $varNameAttr) . "};\n"
            . 'const expressions = ' . json_encode(array_keys(self::EXPECTED)) . ";\n"
            . "console.log(JSON.stringify(expressions.map(function(expression) { return String(LEMval(expression)); })));\n";

        $jsFile = tempnam(\Yii::app()->getConfig('tempdir'), 'lemval');
        file_put_contents($jsFile, $js);
        $output = [];
        exec('node -e ' . escapeshellarg("const fs = require('fs'); eval(fs.readFileSync(" . json_encode($jsFile) . ", {encoding: 'utf8'}));") . ' 2>&1', $output);
        unlink($jsFile);

        $results = json_decode(implode("\n", $output), true);
        $this->assertIsArray($results, implode("\n", $output));
        $this->assertSame(array_values(self::EXPECTED), $results);
    }

    /**
     * Process an expression string without the tailoring markup
     * @param string $string
     * @return string
     */
    private function processString(string $string): string
    {
        return \LimeExpressionManager::ProcessString($string, null, [], 1, 1, false, false, true);
    }

    /**
     * Start the survey in survey mode and set the test responses
     * @param bool $assessments Whether assessments are active
     * @return array<string, string> Fieldnames by question code and subquestion code
     */
    private function startSurveyWithResponses(bool $assessments): array
    {
        \Yii::app()->setConfig('surveyID', self::$surveyId);
        \Yii::app()->setController(new DummyController('dummyid'));
        $_SESSION['LEMsid'] = self::$surveyId;
        \buildsurveysession(self::$surveyId);
        $surveyOptions = self::$testHelper->getSurveyOptions(self::$surveyId);
        $surveyOptions['assessments'] = $assessments;
        \LimeExpressionManager::StartSurvey(self::$surveyId, 'survey', $surveyOptions, true, 0);
        \LimeExpressionManager::NavigateForwards();

        $fieldnames = [];
        foreach (\createFieldMap(\Survey::model()->findByPk(self::$surveyId), 'full', false, false) as $field) {
            if (!empty($field['aid'])) {
                $fieldnames[$field['title'] . '_' . $field['aid']] = $field['fieldname'];
            }
        }
        foreach (self::RESPONSES as $code => $value) {
            $_SESSION['responses_' . self::$surveyId][$fieldnames[$code]] = $value;
        }
        return $fieldnames;
    }
}
